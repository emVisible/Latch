import fs from "node:fs/promises";
import path from "node:path";
import { LATCH_ROOT } from "./paths.js";

export type HookPlan = {
  files: { path: string; content: string; executable?: boolean }[];
  warnings: string[];
};

const MARKER = "latch-managed";

function shellJson(value: unknown): string {
  return JSON.stringify(value).replace(/'/g, "'\\''");
}

function script(
  routeName: string,
  window: string,
  mode: "prompt" | "tool" | "git",
): string {
  const allow =
    mode === "prompt"
      ? shellJson({ continue: true })
      : shellJson({ permission: "allow" });
  const deny =
    mode === "prompt"
      ? shellJson({
          continue: false,
          user_message: `Latch route ${routeName} 未通过，请先修复后重试。详情见 .latch/last-route.json`,
        })
      : shellJson({
          permission: "deny",
          user_message: `Latch route ${routeName} 未通过，请先修复后重试`,
          agent_message: `Latch 静态域未通过；不要绕过 hook，先查看 .latch/last-route.json 并修复`,
        });

  const head = `#!/bin/sh
# ${MARKER}: generated by Latch. Regenerate with: latch hooks install --target <id>
LATCH_ROOT=${shellJson(LATCH_ROOT)}
ROUTE=${shellJson(routeName)}
REPO="\${CURSOR_PROJECT_DIR:-\${CLAUDE_PROJECT_DIR:-\$(pwd)}}"
mkdir -p "$REPO/.latch"
SESS_FILE="$REPO/.latch/hook-session"
if [ ! -s "$SESS_FILE" ]; then
  od -An -N16 -tx1 /dev/urandom | tr -d ' \\n' > "$SESS_FILE"
fi
SESS=$(cat "$SESS_FILE")
cd "$LATCH_ROOT" || { printf '%s\\n' '${deny}'; exit 2; }
node --import tsx ./cli/run.ts route "$ROUTE" --cwd "$REPO" --window ${shellJson(window)} --session "$SESS" >/dev/null 2>&1
code=$?
`;
  if (mode === "git") {
    return `${head}if [ "$code" -ne 0 ]; then
  echo "Latch route $ROUTE 未通过（exit $code），详情见 .latch/last-route.json" >&2
fi
exit "$code"
`;
  }
  return `${head}if [ "$code" -eq 0 ]; then
  printf '%s\\n' '${allow}'
  exit 0
fi
printf '%s\\n' '${deny}'
exit 2
`;
}

export function compileCursorHooks(routeName: string): string {
  return `${JSON.stringify(
    {
      version: 1,
      hooks: {
        beforeSubmitPrompt: [
          {
            command: ".cursor/hooks/latch-route-prompt.sh",
            matcher: "UserPromptSubmit",
            failClosed: true,
          },
        ],
        preToolUse: [
          {
            command: ".cursor/hooks/latch-route-tool.sh",
            matcher: "Write|Edit|Delete|Shell",
            failClosed: true,
          },
        ],
      },
      _latch: { managedBy: "latch", route: routeName },
    },
    null,
    2,
  )}\n`;
}

export function compileClaudeHooks(routeName: string): Record<string, unknown> {
  const group = (matcher: string, scriptName: string) => ({
    matcher,
    hooks: [
      {
        type: "command",
        command: `.claude/hooks/${scriptName}`,
        onFailure: "block",
      },
    ],
  });
  return {
    hooks: {
      UserPromptSubmit: [group("UserPromptSubmit", "latch-route-prompt.sh")],
      PreToolUse: [group("Write|Edit|Bash", "latch-route-tool.sh")],
    },
    _latch: { managedBy: "latch", route: routeName },
  };
}

/** Merge our entries into existing hook configs instead of clobbering them. */
function mergeHookArray(
  existing: unknown,
  incoming: Record<string, unknown>[],
): Record<string, unknown>[] {
  const kept = Array.isArray(existing)
    ? (existing as Record<string, unknown>[]).filter(
        (e) => !String(e.command ?? "").includes("latch-route-"),
      )
    : [];
  return [...kept, ...incoming];
}

export async function buildHookPlan(
  repo: string,
  routeName: string,
  options: { window?: string } = {},
): Promise<HookPlan> {
  const window = options.window ?? "worktree";
  const warnings: string[] = [];
  const files: HookPlan["files"] = [];

  const cursorPath = path.join(repo, ".cursor", "hooks.json");
  let cursorRaw = compileCursorHooks(routeName);
  try {
    const parsed = JSON.parse(await fs.readFile(cursorPath, "utf8")) as Record<
      string,
      unknown
    >;
    const hooks = (parsed.hooks ?? {}) as Record<string, unknown>;
    const generated = JSON.parse(compileCursorHooks(routeName)) as {
      hooks: Record<string, Record<string, unknown>[]>;
    };
    parsed.version = 1;
    parsed.hooks = {
      ...hooks,
      beforeSubmitPrompt: mergeHookArray(
        hooks.beforeSubmitPrompt,
        generated.hooks.beforeSubmitPrompt,
      ),
      preToolUse: mergeHookArray(hooks.preToolUse, generated.hooks.preToolUse),
    };
    parsed._latch = { managedBy: "latch", route: routeName };
    cursorRaw = `${JSON.stringify(parsed, null, 2)}\n`;
  } catch {
    /* no existing config: write a fresh one */
  }
  files.push({ path: cursorPath, content: cursorRaw });
  files.push({
    path: path.join(repo, ".cursor", "hooks", "latch-route-prompt.sh"),
    content: script(routeName, window, "prompt"),
    executable: true,
  });
  files.push({
    path: path.join(repo, ".cursor", "hooks", "latch-route-tool.sh"),
    content: script(routeName, window, "tool"),
    executable: true,
  });

  const claudePath = path.join(repo, ".claude", "settings.json");
  let claude = compileClaudeHooks(routeName);
  try {
    const parsed = JSON.parse(await fs.readFile(claudePath, "utf8")) as Record<
      string,
      unknown
    >;
    const hooks = (parsed.hooks ?? {}) as Record<string, unknown>;
    const generated = compileClaudeHooks(routeName).hooks as Record<
      string,
      Record<string, unknown>[]
    >;
    parsed.hooks = {
      ...hooks,
      UserPromptSubmit: mergeHookGroups(
        hooks.UserPromptSubmit,
        generated.UserPromptSubmit,
      ),
      PreToolUse: mergeHookGroups(hooks.PreToolUse, generated.PreToolUse),
    };
    parsed._latch = { managedBy: "latch", route: routeName };
    claude = parsed;
  } catch {
    /* no existing config */
  }
  files.push({ path: claudePath, content: `${JSON.stringify(claude, null, 2)}\n` });
  files.push({
    path: path.join(repo, ".claude", "hooks", "latch-route-prompt.sh"),
    content: script(routeName, window, "prompt"),
    executable: true,
  });
  files.push({
    path: path.join(repo, ".claude", "hooks", "latch-route-tool.sh"),
    content: script(routeName, window, "tool"),
    executable: true,
  });

  const gitHook = path.join(repo, ".git", "hooks", "pre-commit");
  let gitContent = "";
  try {
    gitContent = await fs.readFile(gitHook, "utf8");
  } catch {
    gitContent = "";
  }
  if (gitContent.trim() && !gitContent.includes(MARKER)) {
    warnings.push(
      `已存在非 Latch 的 pre-commit hook，未覆盖：${gitHook}。请手动把 .git/hooks/pre-commit.latch 的内容并入`,
    );
    files.push({
      path: path.join(repo, ".git", "hooks", "pre-commit.latch"),
      content: script(routeName, "staged", "git"),
      executable: true,
    });
  } else {
    files.push({
      path: gitHook,
      content: script(routeName, "staged", "git"),
      executable: true,
    });
  }

  return { files, warnings };
}

function mergeHookGroups(
  existing: unknown,
  incoming: Record<string, unknown>[],
): Record<string, unknown>[] {
  const kept = Array.isArray(existing)
    ? (existing as Record<string, unknown>[]).filter((group) => {
        const list = group.hooks;
        return !(
          Array.isArray(list) &&
          list.some((h) =>
            String((h as Record<string, unknown>).command ?? "").includes(
              "latch-route-",
            ),
          )
        );
      })
    : [];
  return [...kept, ...incoming];
}

export async function installHooks(
  repo: string,
  routeName: string,
  options: { window?: string } = {},
): Promise<{ written: string[]; warnings: string[] }> {
  const plan = await buildHookPlan(repo, routeName, options);
  const written: string[] = [];
  for (const file of plan.files) {
    await fs.mkdir(path.dirname(file.path), { recursive: true });
    await fs.writeFile(file.path, file.content, "utf8");
    if (file.executable) await fs.chmod(file.path, 0o755);
    written.push(file.path);
  }
  return { written, warnings: plan.warnings };
}

export async function hookStatus(repo: string): Promise<string[]> {
  const checks = [
    ".cursor/hooks.json",
    ".cursor/hooks/latch-route-prompt.sh",
    ".cursor/hooks/latch-route-tool.sh",
    ".claude/settings.json",
    ".git/hooks/pre-commit",
  ];
  const out: string[] = [];
  for (const rel of checks) {
    try {
      await fs.access(path.join(repo, rel));
      out.push(`ok  ${rel}`);
    } catch {
      out.push(`--  ${rel}（未安装）`);
    }
  }
  return out;
}
